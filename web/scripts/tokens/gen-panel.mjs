import { palettes, series } from './palettes.mjs';
import { writeFileSync } from 'node:fs';
const decl = (t, mode) => '\n  color-scheme: ' + mode + ';\n  ' + Object.entries(t).map(([k,v])=>`--${k}: ${v};`).reduce((a,d,i)=>a+(i&&i%6===0?'\n  ':i?' ':'')+d,'') +
  '\n  ' + series[mode].map((c,i)=>`--s${i+1}: ${c};`).join(' ') +
  (mode==='dark' ? '\n  --shadow-card: none; --shadow-pop: 0 0 0 1px var(--border-strong), 0 12px 32px rgb(0 0 0 / .45);'
                 : '\n  --shadow-card: 0 1px 2px rgb(16 18 24 / .05); --shadow-pop: 0 8px 24px rgb(16 18 24 / .12);') + '\n';
let css = `/* ---- colour tokens (docs/DESIGN.md "Colour system") ----
   Generated by web/scripts/tokens (node gen-panel.mjs) from palettes.mjs; every text/UI pair is checked against base, surface,
   overlay and raised (text, subtle >= 4.5:1, muted >= 3:1 (>= 4.1 in practice), border-strong >= 3:1).
   <html data-palette="neutral|rosepine|catppuccin|nord" data-theme="light|dark" (absent = follow system)>.
   Chart series --s1..--s8 keep their validated order and values in every palette. */
`;
const N = palettes.neutral;
css += `:root {${decl(N.light,'light')}}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {${decl(N.dark,'dark').replace(/\n/g,'\n  ')}}\n}\n`;
css += `:root[data-theme="dark"] {${decl(N.dark,'dark')}}\n`;
for (const [k,p] of Object.entries(palettes)) { if (k==='neutral') continue;
  css += `:root[data-palette="${k}"] {${decl(p.light,'light')}}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  :root[data-palette="${k}"]:not([data-theme="light"]) {${decl(p.dark,'dark').replace(/\n/g,'\n  ')}}\n}\n`;
  css += `:root[data-palette="${k}"][data-theme="dark"] {${decl(p.dark,'dark')}}\n`;
}
css += `:root {
  --accent-soft: color-mix(in oklab, var(--accent) 14%, var(--surface));
  --good-soft: color-mix(in oklab, var(--good) 14%, var(--surface));
  --warn-soft: color-mix(in oklab, var(--warn) 16%, var(--surface));
  --bad-soft: color-mix(in oklab, var(--bad) 14%, var(--surface));
}
`;
// Paste the output over the colour-token block in web/src/index.css, and copy it to
// internal/master/subtheme/default/tokens.css (the default subscription theme uses the same palettes).
writeFileSync('panel-tokens.css', css);
console.log('wrote panel-tokens.css');
